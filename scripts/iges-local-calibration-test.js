const assert = require('assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { describeImage, compareImages, cropImage, runLocalCalibration, applyRenderGates, selectEligibleFinal } = require('../utils/igesLocalCalibration');
const { extractIgesSubfigureNames, buildControlledFixtureBinding, runIgesSourcePipeline, detectIgesUnits, buildDatabaseSourceRecord } = require('../utils/igesSourcePipeline');
const rectangle = (width, height, rw, rh) => {
  const data = Buffer.alloc(width * height * 4, 255);
  for (let y = Math.floor((height - rh) / 2); y < (height + rh) / 2; y++) for (let x = Math.floor((width - rw) / 2); x < (width + rw) / 2; x++) {
    const i = (y * width + x) * 4; data[i] = data[i + 1] = data[i + 2] = 70;
  }
  return { width, height, data };
};
(async () => {
  const globalRecord = (flag, unit, delimiter = ',', terminator = ';', modelScale = 1) => {
    const h = value => `${value.length}H${value}`;
    const fields = [h(delimiter), h(terminator), h('Product contains 2HMM and 2HIN'), h('2HMM-misleading-name.IGS'), h('native'), h('processor'), '32', '38', '6', '308', '15', h('receiver'), String(modelScale), String(flag), h(unit)];
    const text = fields.join(delimiter) + terminator;
    const lines = []; for (let i = 0; i < text.length; i += 72) lines.push(text.slice(i, i + 72).padEnd(72) + 'G      1');
    return lines.join('\n');
  };
  assert.equal(detectIgesUnits(globalRecord(1, 'IN')), 'inch', 'Product/file text cannot override Global units');
  assert.equal(detectIgesUnits(globalRecord(2, 'MM', '^', '!')), 'millimeter');
  assert.equal(detectIgesUnits(globalRecord(1, 'MM')), 'unknown', 'Flag/name disagreement must fail closed');
  assert.equal(detectIgesUnits(globalRecord(4, 'FT')), 'unknown', 'Unsupported native units must fail closed');
  assert.equal(detectIgesUnits(globalRecord(2, 'MM', ',', ';', 2)), 'unknown', 'Unimplemented model scale must fail closed');
  assert.equal(detectIgesUnits('product 2HMM'), 'unknown');
  assert.equal(selectEligibleFinal(null, { comparison: { visual_fidelity_score: null, gateReasons: ['clipped'] } }), null);
  const validCandidate = { comparison: { visual_fidelity_score: 42, gateReasons: [] } };
  assert.equal(selectEligibleFinal(validCandidate, { comparison: { visual_fidelity_score: null } }), validCandidate);
  const blank = describeImage(rectangle(100, 100, 0, 0));
  assert.equal(compareImages(blank, blank).visual_fidelity_score, null, 'Blank backgrounds must be unscorable');
  const wide = describeImage(rectangle(100, 100, 80, 20));
  const tall = describeImage(rectangle(100, 100, 20, 80));
  assert(compareImages(wide, wide).visual_fidelity_score > 99);
  assert(compareImages(wide, tall).visual_fidelity_score < 35, 'Wrong silhouette cannot earn high photometric score');
  assert.throws(() => cropImage(rectangle(20, 20, 5, 5), { x: 0, y: 0, width: 21, height: 10 }), /Invalid view crop/);
  assert.equal(cropImage(rectangle(20, 20, 5, 5), { x: 1, y: 2, width: 3, height: 4 }).data.length, 48);
  const name = 'Arbitrary, component with a long name spanning parameter records';
  const parameter = `308,0,${name.length}H${name},1,99;`;
  const lines = []; for (let i = 0; i < parameter.length; i += 64) lines.push(parameter.slice(i, i + 64).padEnd(64) + '       1P      1');
  assert.deepEqual(extractIgesSubfigureNames(lines.join('\n')), [name]);
  assert.deepEqual(extractIgesSubfigureNames('1Hfixture,bracket-1'), []);
  const binding = buildControlledFixtureBinding();
  assert(binding.ok, binding.reason);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'iges-calibration-test-'));
  await assert.rejects(runIgesSourcePipeline({ sourceBinding: { ...binding, sourceAsset: { ...binding.sourceAsset, expectedUnits: 'inch' } }, outputDir: path.join(dir, 'invalid-unit') }), /unit binding mismatch/);
  await assert.rejects(runIgesSourcePipeline({ sourceBinding: { ...binding, sourceAsset: { ...binding.sourceAsset, approvedSha256: '0'.repeat(64) } }, outputDir: path.join(dir, 'changed-source') }), /checksum changed/);
  await assert.rejects(runLocalCalibration({ sources: [], outputDir: dir }), /1–20/);
  await assert.rejects(runLocalCalibration({ sources: [{ id: '../escape' }], outputDir: dir }), /Unsafe artifact ID/);
  const invisible = { ...binding, renderPreset: { ...binding.renderPreset, displayState: { visible: false } } };
  await assert.rejects(runIgesSourcePipeline({ sourceBinding: invisible, outputDir: path.join(dir, 'invisible') }), /No visible geometry/);
  const invalidBasis = { ...binding, renderPreset: { ...binding.renderPreset, projection: { mode: 'basis', viewDirection: [0,1,0], upDirection: [0,1,0] } } };
  await assert.rejects(runIgesSourcePipeline({ sourceBinding: invalidBasis, outputDir: path.join(dir, 'invalid-basis') }), /independent/);
  const clipped = applyRenderGates({ visual_fidelity_score: 99 }, { viewport: { allVisibleGeometryWithinFrame: false }, visibleNodePixels: {} }, { touchesCanvas: false });
  assert.equal(clipped.visual_fidelity_score, null);
  const missingComponent = applyRenderGates({ visual_fidelity_score: 99 }, { viewport: { allVisibleGeometryWithinFrame: true }, visibleNodePixels: { reel: 0 } }, { touchesCanvas: false }, ['reel']);
  assert.equal(missingComponent.visual_fidelity_score, null);
  const noReference = await runLocalCalibration({ sources: [{ id: binding.sourceAsset.id, record: buildDatabaseSourceRecord(), references: [] }], outputDir: path.join(dir, 'no-reference') });
  assert.equal(noReference.assets[0].visualAssessment, 'not_assessed_no_reference');
  assert.equal(noReference.assets[0].views.length, 0);
  assert(noReference.trace.every(item => !item.candidateCount));
  // Finalization must ignore stale/tampered derived pixels and rederive from raw.
  const { PNG } = require('pngjs');
  const crypto = require('crypto');
  const cp = require('child_process');
  const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  const base = noReference.assets[0].baseline;
  const rawPath = path.join(dir, 'raw.png'); fs.copyFileSync(base.render.outputPath, rawPath);
  const stalePath = path.join(dir, 'stale.png'); fs.writeFileSync(stalePath, PNG.sync.write(rectangle(100, 100, 0, 0)));
  const priorPath = path.join(dir, 'prior.json');
  const prior = { trace: [], assets: [{ id: binding.sourceAsset.id, baseline: base, unmatchedReferences: [], views: [{ id: 'test', provenance: { path: rawPath, sha256: hash(rawPath), kind: 'standalone_view' }, referenceArtifact: stalePath, baselineComparison: {}, residualIssues: [], best: { preset: base.renderPreset, render: base.render, comparison: { visual_fidelity_score: 1 } } }] }] };
  const finalizeManifest = { outputDir: path.join(dir, '.local', 'finalized'), reportPaths: [priorPath], sources: [{ id: binding.sourceAsset.id, record: buildDatabaseSourceRecord(), references: [{ id: 'test', path: rawPath, sha256: hash(rawPath), kind: 'standalone_view' }] }] };
  const manifestPath = path.join(dir, 'finalize.json');
  const runFinalizer = () => {
    fs.writeFileSync(priorPath, JSON.stringify(prior)); fs.writeFileSync(manifestPath, JSON.stringify(finalizeManifest));
    const processResult = cp.spawnSync(process.execPath, ['scripts/iges-local-calibration-finalize.js', manifestPath], { encoding: 'utf8' });
    assert.equal(processResult.status, 0, processResult.stderr);
    return JSON.parse(fs.readFileSync(path.join(finalizeManifest.outputDir, 'report.json'))).assets[0].views[0];
  };
  const regenerated = runFinalizer();
  assert.deepEqual(PNG.sync.read(fs.readFileSync(regenerated.referenceArtifact)).data, PNG.sync.read(fs.readFileSync(rawPath)).data);
  assert.equal(regenerated.validation.status, 'ready_for_human_semantic_review');
  fs.copyFileSync(stalePath, rawPath);
  prior.assets[0].views[0].provenance.sha256 = hash(rawPath);
  finalizeManifest.sources[0].references[0].sha256 = hash(rawPath);
  const unscorable = runFinalizer();
  assert.equal(unscorable.validation.status, 'blocked');
  assert.equal(unscorable.best, null);
  console.log('Local calibration negative/unit tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
